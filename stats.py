def cross_dev(X, wid):
    """Deviation from orthogonality (degrees) of every cross-word pair, ascending,
    with the (i, j) row indices in the same order."""
    G = (X @ X.T).abs().clamp(max=1.0)
    m = (wid[:, None] != wid[None, :]).triu(1)
    v, ij = torch.rad2deg(torch.asin(G[m])), m.nonzero().to(torch.int32)
    del G, m
    order = v.argsort()
    return v[order], ij[order]


def quants(v):
    """(p50, p99.9, max) of an ascending vector."""
    n = len(v)
    return v[int(0.5 * (n - 1))].item(), v[int(0.999 * (n - 1))].item(), v[-1].item()


def ci(vals):
    s = sorted(vals)
    return s[int(0.025 * (len(s) - 1))], s[int(0.975 * (len(s) - 1))]


def spectrum(M):
    """(participation ratio, λ₁ share, top-16 share) of the squared singular
    values of M via the d×d Gram. PR comes from trace and Frobenius norm in
    fp64; the fp32 eigenvalues only feed the top-k shares."""
    G = M.T @ M
    s2 = torch.linalg.eigvalsh(G).flip(0).clamp(min=0)
    pr = G.diagonal().double().sum() ** 2 / (G.double() ** 2).sum()
    return pr.item(), (s2[0] / s2.sum()).item(), (s2[:16].sum() / s2.sum()).item()


def null_b(X, wid, seed):
    Xc = X - X.mean(0)
    L = torch.linalg.cholesky(Xc.T @ Xc / len(Xc) + 1e-6 * torch.eye(X.shape[1], device=dev))
    g = torch.Generator(device=dev).manual_seed(seed)
    Z = torch.nn.functional.normalize(torch.randn(X.shape, generator=g, device=dev) @ L.T + X.mean(0), dim=1)
    return quants(cross_dev(Z, wid)[0])


def boot_ci(v, ij, clusters, seed):
    """Cluster-bootstrap 95% CIs of p50 / p99.9 over words. Resampling words
    with replacement multiplies pair (i, j) by m[w_i]·m[w_j], so each resample
    is a weighted quantile over the fixed sorted pairs, not a new Gram.
    Same-word pairs are excluded, so every pair has expected weight 1."""
    ids, cl = clusters.unique(return_inverse=True)
    ci_, cj_ = cl[ij[:, 0]].to(torch.int32), cl[ij[:, 1]].to(torch.int32)
    ps = torch.tensor([0.5, 0.999], dtype=torch.float64, device=dev)
    gb = torch.Generator(device="cpu").manual_seed(seed)
    qs = []
    for _ in range(BOOT):
        pick = torch.randint(len(ids), (len(ids),), generator=gb)
        mult = torch.bincount(pick, minlength=len(ids)).to(dev, torch.float32)
        cum = (mult[ci_] * mult[cj_]).cumsum(0, dtype=torch.float64)
        qs.append(v[torch.searchsorted(cum, cum[-1] * ps).clamp(max=len(v) - 1)])
    q50, q999 = torch.stack(qs).T.tolist()
    return ci(q50), ci(q999)


def jack_ci(v, ij, clusters):
    """Delete-one-cluster jackknife 95% CIs of p50 / p99.9 over blocks. A block
    bootstrap is biased here: within-block (shared-cue) pairs get weight
    m_b^2 with E = 2 against 1 for cross-block pairs, so the tail quantile is
    pulled toward the shared-cue population. Deleting one block at a time
    never duplicates a pair."""
    ids, cl = clusters.unique(return_inverse=True)
    ci_, cj_ = cl[ij[:, 0]], cl[ij[:, 1]]
    ps = torch.tensor([0.5, 0.999], dtype=torch.float64, device=dev)
    qs = []
    for b in range(len(ids)):
        keep = ((ci_ != b) & (cj_ != b)).to(torch.float64)
        cum = keep.cumsum(0)
        qs.append(v[torch.searchsorted(cum, cum[-1] * ps).clamp(max=len(v) - 1)])
    Q = torch.stack(qs).double()
    n = len(ids)
    se = ((n - 1) / n * ((Q - Q.mean(0)) ** 2).sum(0)).sqrt()
    full = torch.tensor([v[int(0.5 * (len(v) - 1))], v[int(0.999 * (len(v) - 1))]], dtype=torch.float64, device=dev)
    lo, hi = (full - 1.96 * se).tolist(), (full + 1.96 * se).tolist()
    return (lo[0], hi[0]), (lo[1], hi[1])


def dev_row(a, dd):
    keys = sorted(a["cents"])
    X = torch.stack([a["cents"][k] for k in keys]).to(dev)
    wid = torch.tensor([k[0] for k in keys], device=dev)
    rk = torch.tensor([k[1] for k in keys], device=dev)
    blk = (wid * a["config"]["k"] + rk - 1) % a["config"]["n_blocks"]
    seed = a["config"]["seed"]
    g = torch.Generator().manual_seed(seed)
    R = torch.nn.functional.normalize(torch.randn(len(keys), dd, generator=g), dim=-1).to(dev)
    r50, r999, _ = quants(cross_dev(R, torch.arange(len(keys), device=dev))[0])
    del R
    v, ij = cross_dev(X, wid)
    p50, p999, pmax = quants(v)
    P = spectrum(X - X.mean(0))[0]
    w50, w999 = boot_ci(v, ij, wid, 1000 + seed)
    k50, k999 = jack_ci(v, ij, blk)
    del v, ij
    b50, b999, bmax = null_b(X, wid, 3000 + seed)
    deff = math.degrees(math.asin(0.6745 / math.sqrt(P)))
    return dict(P=P, p50=p50, p999=p999, pmax=pmax, r50=r50, r999=r999, w50=w50, w999=w999, k50=k50, k999=k999,
                b50=b50, b999=b999, bmax=bmax, deff=deff)



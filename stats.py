def spread(vals, fmt="{:.3f}"):
    v = sorted(vals)
    med = v[len(v) // 2] if len(v) % 2 else (v[len(v) // 2 - 1] + v[len(v) // 2]) / 2
    if len(v) == 1:
        return fmt.format(v[0]) + " (n=1)"
    return f"{fmt.format(med)} [{fmt.format(v[0])}, {fmt.format(v[-1])}] n={len(v)}"


